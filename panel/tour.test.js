    assert.deepEqual([pts[0].x, pts[0].y], [g.items[i].a.x, g.items[i].a.y], `${g.w}px, ${NAMES[i]}: начинается у конца строки`);
    const end = pts[pts.length - 1];
    assert.ok(Math.abs(end.x - g.items[i].bx) < 0.01 && Math.abs(end.y - g.items[i].by) < 0.01, `${g.w}px, ${NAMES[i]}: приходит к кнопке`);
